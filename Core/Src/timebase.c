/*
 * timebase.c  -  HAL 1 ms time base on TIM4
 *
 * FreeRTOS owns SysTick, so the HAL needs its own time base.  It is only used
 * for the timeouts of the blocking I2C transfers and for HAL_Delay.
 * HAL_RCC_ClockConfig() calls HAL_InitTick() again after the clock switch, so
 * the prescaler is always recomputed for the real APB1 frequency.
 */
#include "main.h"
#include "watch.h"
#include "FreeRTOS.h"
#include "FreeRTOSConfig.h"

TIM_HandleTypeDef htim4;

HAL_StatusTypeDef HAL_InitTick(uint32_t TickPriority)
{
	RCC_ClkInitTypeDef clkconfig;
	uint32_t           uwTimclock;
	uint32_t           uwAPB1Prescaler;
	uint32_t           uwPrescalerValue;
	uint32_t           pFLatency;
	HAL_StatusTypeDef  status;

	__HAL_RCC_TIM4_CLK_ENABLE();

	HAL_RCC_GetClockConfig(&clkconfig, &pFLatency);
	uwAPB1Prescaler = clkconfig.APB1CLKDivider;

	if (uwAPB1Prescaler == RCC_HCLK_DIV1)
		uwTimclock = HAL_RCC_GetPCLK1Freq();
	else
		uwTimclock = 2UL * HAL_RCC_GetPCLK1Freq();

	/* 1 MHz counter clock -> 1 ms period */
	uwPrescalerValue = (uint32_t)((uwTimclock / 1000000U) - 1U);

	htim4.Instance               = TIM4;
	htim4.Init.Period            = (1000000U / 1000U) - 1U;
	htim4.Init.Prescaler         = uwPrescalerValue;
	htim4.Init.ClockDivision     = 0;
	htim4.Init.CounterMode       = TIM_COUNTERMODE_UP;
	htim4.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_DISABLE;

	status = HAL_TIM_Base_Init(&htim4);
	if (status != HAL_OK) return status;

	status = HAL_TIM_Base_Start_IT(&htim4);
	if (status != HAL_OK) return status;

	if (TickPriority < (1UL << __NVIC_PRIO_BITS))
	{
		/* lowest priority: the HAL tick must never preempt the RTOS */
		HAL_NVIC_SetPriority(TIM4_IRQn, configLIBRARY_LOWEST_INTERRUPT_PRIORITY, 0U);
		uwTickPrio = TickPriority;
	}
	else
	{
		status = HAL_ERROR;
	}

	HAL_NVIC_EnableIRQ(TIM4_IRQn);
	return status;
}

void HAL_SuspendTick(void)
{
	__HAL_TIM_DISABLE_IT(&htim4, TIM_IT_UPDATE);
}

void HAL_ResumeTick(void)
{
	__HAL_TIM_ENABLE_IT(&htim4, TIM_IT_UPDATE);
}

/* TIM4 update -> the HAL millisecond tick */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
	if (htim->Instance == TIM4)
	{
		HAL_IncTick();
	}
}

/* the Msp hook is normally generated by CubeMX; TIM4 needs no extra setup */
void HAL_TIM_Base_MspInit(TIM_HandleTypeDef *htim)
{
	if (htim->Instance == TIM4)
	{
		__HAL_RCC_TIM4_CLK_ENABLE();
	}
}
